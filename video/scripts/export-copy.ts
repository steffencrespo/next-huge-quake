/**
 * Writes every on-screen string for each fixture, scene by scene, to out/copy-review.md for editorial review.
 * Also runs the copy guard and reports its result.
 *
 * Usage: tsx scripts/export-copy.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { checkScreenText } from '../src/copy/guard.js';
import { allScreenText, buildScreenCopy } from '../src/copy/screenCopy.js';
import type { ContextCard } from '../src/copy/screenCopy.js';
import { BRAND } from '../src/design/brand.js';
import { DEMO_AS_OF_UTC, FIXTURES } from '../src/fixtures/index.js';
import { CONTEXT_PRIORITY, buildVideoSpec } from '../src/spec/build.js';
import { contextItemSupported } from '../src/spec/schema.js';
import type { SceneKind, VideoSpec } from '../src/spec/schema.js';
import { sceneRanges } from '../src/spec/timeline.js';

const root = join( dirname( new URL( import.meta.url ).pathname ), '..' );
const out = join( root, 'out' );
mkdirSync( out, { recursive: true } );

/** "Facts (6–18 s)", from the spec's scene ranges. */
const heading = ( spec: VideoSpec, kind: SceneKind, title: string ) => {
  const range = sceneRanges( spec ).find( r => r.kind === kind )!;
  const fps = spec.format.fps;
  return `### ${title} (${range.from / fps}–${( range.from + range.durationInFrames ) / fps} s)`;
};
const show = ( value: string | null ) => value === null ? '_(not shown)_' : value;
const card = ( c: ContextCard ) => [
  `**${c.title}: ${c.value}**`, '',
  `- ${c.line}`,
  `- ${show( c.note )}`,
  ...( c.extended ? [ `- _Extended (not displayed in the video):_ ${c.extended}` ] : [] ), ''
];
const lines: string[] = [ '# Screen copy review', '', `Generated by \`scripts/export-copy.ts\` from the VideoSpec fixtures. Live-map mode, produced as of ${DEMO_AS_OF_UTC}. Context cards show title: value, the on-screen line, then the on-screen caveat.`, '' ];

for ( const [ key, fixture ] of Object.entries( FIXTURES ) ) {
  const spec = buildVideoSpec( fixture, { asOfUtc: DEMO_AS_OF_UTC } );
  const copy = buildScreenCopy( spec );
  const issues = checkScreenText( allScreenText( copy ), spec.event );
  // Cards the facts support but the three-card limit left out, rendered from the same templates for review.
  const unused = CONTEXT_PRIORITY.filter( item => contextItemSupported( item, spec.event ) && !spec.scenes[2].items.includes( item ) );
  const unusedCards = unused.length === 0 ? [] : buildScreenCopy( {
    ...spec, scenes: [ spec.scenes[0], spec.scenes[1], { ...spec.scenes[2], items: unused.slice( 0, 3 ) }, spec.scenes[3] ]
  } ).context.cards;
  lines.push(
    `## ${key} (${spec.event.id}, ${spec.provenance}, source ${fixture.source})`, '',
    `Guard: ${issues.length === 0 ? 'pass' : `**${issues.length} issue(s)**: ${issues.map( i => `${i.problem} in "${i.text}"` ).join( '; ' )}`}`, '',
    '### Persistent chrome (every scene)', '',
    `- Tag: ${copy.chrome.tag}`,
    `- Archive indicator (from frame 0): ${copy.chrome.archive ? `${copy.chrome.archive.badge} · ${copy.chrome.archive.detail}` : '_(not shown: recent event)_'}`,
    `- Update timestamp: ${copy.chrome.updated}`,
    `- Footer: ${copy.chrome.source}`,
    `- Preliminary badge: ${copy.chrome.preliminary ? `${copy.chrome.preliminary.badge} · ${copy.chrome.preliminary.detail}` : '_(not shown: reviewed)_'}`,
    `- Test watermark: ${show( copy.chrome.testData )}`, '',
    `- Location: ${copy.location.name === null ? `no USGS place name (coordinate fallback ${copy.location.coordinates}; later layouts avoid repeating it)` : `${copy.location.name} · ${copy.location.coordinates}`}`, '',
    heading( spec, 'hook', 'Hook' ), '',
    `- ${copy.hook.kicker}`,
    `- ${copy.hook.magnitude}${copy.hook.magType ? ` (${copy.hook.magType})` : ''}`,
    `- ${copy.hook.place}`,
    `- ${copy.hook.when}`, '',
    heading( spec, 'facts', 'Facts' ), '',
    `- Lower third: ${copy.facts.lowerThird.kicker} / ${copy.facts.lowerThird.title} / ${copy.facts.lowerThird.subtitle}`,
    '', '| Label | Value | Detail |', '|---|---|---|',
    ...copy.facts.rows.map( r => `| ${r.label} | ${r.value} | ${show( r.detail )} |` ), '',
    heading( spec, 'context', 'Context' ), '',
    ...copy.context.cards.flatMap( card ),
    ...( unusedCards.length === 0 ? [] : [
      '_Also supported by the facts, but not shown (three-card limit):_', '',
      ...unusedCards.flatMap( card )
    ] ),
    heading( spec, 'closing', 'Closing' ), '',
    `- Wordmark: ${BRAND.name}`,
    `- Tagline: ${BRAND.tagline ?? '_(none)_'}`,
    `- ${copy.closing.source}`,
    `- ${copy.closing.eventId}`,
    `- ${copy.closing.url}`,
    `- ${copy.closing.updated}`,
    `- ${show( copy.closing.mapCredit )}`,
    ...copy.closing.disclaimers.map( d => `- ${d}` ), ''
  );
}

const file = join( out, 'copy-review.md' );
writeFileSync( file, lines.join( '\n' ) );
console.log( `wrote ${file}` );
